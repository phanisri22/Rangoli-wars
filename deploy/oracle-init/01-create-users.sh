#!/bin/bash
# Runs once, when the Oracle container creates its database. One schema per service.
set -e

sqlplus -s / as sysdba <<EOF
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE USER auth_svc IDENTIFIED BY "${AUTH_DB_PASSWORD}" QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO auth_svc;

CREATE USER leaderboard_svc IDENTIFIED BY "${LEADERBOARD_DB_PASSWORD}" QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO leaderboard_svc;
EXIT;
EOF
