CREATE TABLE IF NOT EXISTS player_stats (
    username     VARCHAR2(20) PRIMARY KEY,
    games_played NUMBER(10) DEFAULT 0    NOT NULL,
    wins         NUMBER(10) DEFAULT 0    NOT NULL,
    total_tiles  NUMBER(10) DEFAULT 0    NOT NULL,
    rating       NUMBER(10) DEFAULT 1000 NOT NULL,
    last_played  TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_player_stats_rating ON player_stats (rating DESC, wins DESC);

CREATE TABLE IF NOT EXISTS matches (
    id          NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_code   VARCHAR2(10) NOT NULL,
    board_size  NUMBER(3)    NOT NULL,
    max_rounds  NUMBER(3)    NOT NULL,
    started_at  TIMESTAMP,
    finished_at TIMESTAMP    NOT NULL,
    ended_early NUMBER(1)    DEFAULT 0 NOT NULL,
    total_moves NUMBER(5)    NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_matches_finished ON matches (finished_at DESC);

CREATE TABLE IF NOT EXISTS match_players (
    match_id     NUMBER(19)   NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
    color        NUMBER(1)    NOT NULL,
    username     VARCHAR2(20),
    display_name VARCHAR2(40) NOT NULL,
    is_bot       NUMBER(1)    NOT NULL,
    bot_level    VARCHAR2(10),
    score        NUMBER(5)    NOT NULL,
    placement    NUMBER(1)    NOT NULL,
    PRIMARY KEY (match_id, color)
);

CREATE INDEX IF NOT EXISTS idx_match_players_user ON match_players (username);

CREATE TABLE IF NOT EXISTS match_moves (
    match_id  NUMBER(19)   NOT NULL REFERENCES matches (id) ON DELETE CASCADE,
    turn_no   NUMBER(5)    NOT NULL,
    round_no  NUMBER(3)    NOT NULL,
    color     NUMBER(1)    NOT NULL,
    move_type VARCHAR2(10) NOT NULL,
    r1        NUMBER(2)    NOT NULL,
    c1        NUMBER(2)    NOT NULL,
    r2        NUMBER(2),
    c2        NUMBER(2),
    gained    NUMBER(4)    NOT NULL,
    captured  NUMBER(4)    NOT NULL,
    PRIMARY KEY (match_id, turn_no)
);
